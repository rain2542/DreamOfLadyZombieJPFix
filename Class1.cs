    public class ModMain : MelonMod
    {
        public override void OnInitializeMelon()
        {
            MelonLogger.Msg("JP Fix loaded!");
        }

        public override void OnLateInitializeMelon()
        {
            LocalizationManager.InitializeIfNeeded();

            MelonLogger.Msg($"Localization sources: {LocalizationManager.Sources.Count}");

            if (LocalizationManager.Sources.Count > 0)
            {
                LanguageSourceData source = LocalizationManager.Sources[0];

                string csv = source.Export_CSV(string.Empty);

                string path = Path.Combine(
                    MelonEnvironment.UserDataDirectory,
                    "DreamOfLadyZombie_Localization.csv"
                );

                File.WriteAllText(path, csv);

                MelonLogger.Msg($"Localization CSV exported: {path}");
            }
        }
    }

